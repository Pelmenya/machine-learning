"""
00-intro / 01 — Первая модель: цикл из 6 этапов ML.

Датасет: Breast cancer (встроен в scikit-learn) — по 30 числовым признакам
опухоли предсказываем класс: злокачественная (0) или доброкачественная (1).
Это бинарная классификация — тот же тип задачи, что и любой кейс вида
«выкупит / не выкупит», «уйдёт / останется».

Запуск (из корня репо, окружение активировано):
    python tasks/00-intro/01-first-model/solution.py
"""

# ── Импорты ──────────────────────────────────────────────────
# sklearn разложен на модули: datasets (готовые данные), model_selection
# (деление выборок), linear_model (модели), metrics (оценка качества).
from sklearn.datasets import load_breast_cancer
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score


# ── Этап 1. Подготовка данных ────────────────────────────────
# Загружаем готовый датасет. as_frame=True вернёт данные как pandas DataFrame,
# чтобы было привычно и наглядно (а не «голым» numpy-массивом).
data = load_breast_cancer(as_frame=True)

X = data.data       # признаки: таблица 569 строк × 30 столбцов (по чему предсказываем)
y = data.target     # целевая переменная: 0/1 (что предсказываем)

print("Форма признаков X:", X.shape)          # (569, 30)
print("Названия классов:", list(data.target_names))  # ['malignant', 'benign']
print("Распределение классов:\n", y.value_counts())   # сколько 0 и сколько 1
print("-" * 50)


# ── Этап 2. Деление на обучающую и тестовую выборки ──────────
# Учим модель на одной части, проверяем на другой (которую она «не видела»).
# test_size=0.25 — четверть данных уходит в тест.
# random_state=42 — фиксируем «случайность», чтобы результат воспроизводился.
# stratify=y — сохраняем пропорцию классов в обеих выборках (важно для классиф.).
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, random_state=42, stratify=y
)

print(f"Обучающая выборка: {X_train.shape[0]} строк")
print(f"Тестовая выборка:  {X_test.shape[0]} строк")
print("-" * 50)


# ── Этап 3. Выбор и создание модели ──────────────────────────
# Логистическая регрессия — базовая модель для бинарной классификации.
# max_iter=5000 — даём алгоритму больше итераций, чтобы он успел сойтись
# (на «сырых» признаках без масштабирования сходимость медленнее).
model = LogisticRegression(max_iter=5000)


# ── Этап 4. Обучение ─────────────────────────────────────────
# .fit() — модель смотрит на X_train и y_train и находит закономерности.
model.fit(X_train, y_train)
print("Модель обучена.")
print("-" * 50)


# ── Этап 5. Предсказание ─────────────────────────────────────
# .predict() — модель делает прогнозы для данных, которых раньше не видела.
predictions = model.predict(X_test)
print("Первые 10 предсказаний:", list(predictions[:10]))
print("Реальные ответы:       ", list(y_test[:10]))
print("-" * 50)


# ── Этап 6. Оценка качества ──────────────────────────────────
# accuracy — доля правильных ответов (predictions, совпавших с y_test).
# Сравниваем предсказания с истиной.
accuracy = accuracy_score(y_test, predictions)
print(f"Accuracy на тесте: {accuracy:.4f}  ({accuracy * 100:.2f}% верных предсказаний)")
